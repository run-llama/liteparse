//! TeX math font encodings (OMS = cmsy, OMX = cmex, OML = cmmi, msam):
//! glyph code -> LaTeX, for glyphs PDFium could not map to Unicode.

/// The fixed encoding a TeX math font follows.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Enc {
    Oml,
    Oms,
    Omx,
    Msam,
}

