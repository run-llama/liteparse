/// cmex: big delimiters read as their plain selves (KaTeX renders `\big(`
/// as "("). Extension pieces of tall delimiters: the top piece stands for
/// the delimiter, the rest map to "".
fn omx(code: u32) -> Option<&'static str> {
    const D: [&str; 16] = [
        "(",
        ")",
        "[",
        "]",
        r"\lfloor",
        r"\rfloor",
        r"\lceil",
        r"\rceil",
        r"\{",
        r"\}",
        r"\langle",
        r"\rangle",
        "|",
        r"\|",
        "/",
        r"\backslash",
    ];
    if code < 16 {
        return Some(D[code as usize]);
    }
    Some(match code {
        16 | 18 | 32 | 48 => "(",
        17 | 19 | 33 | 49 => ")",
        20 | 34 | 50 | 104 => "[",
        21 | 35 | 51 | 105 => "]",
        22 | 36 | 106 => r"\lfloor",
        23 | 37 | 107 => r"\rfloor",
        24 | 38 | 108 => r"\lceil",
        25 | 39 | 109 => r"\rceil",
        26 | 40 | 56 | 110 => r"\{",
        27 | 41 | 57 | 111 => r"\}",
        28 | 42 | 68 => r"\langle",
        29 | 43 | 69 => r"\rangle",
        30 | 44 | 46 => "/",
        31 | 45 | 47 => r"\backslash",
        52..=55 | 58..=67 => "",
        70 | 71 => r"\bigsqcup",
        72 | 73 => r"\oint",
        74 | 75 => r"\bigodot",
        76 | 77 => r"\bigoplus",
        78 | 79 => r"\bigotimes",
        80 | 88 => r"\sum",
        81 | 89 => r"\prod",
        82 | 90 => r"\int",
        83 | 91 => r"\bigcup",
        84 | 92 => r"\bigcap",
        85 | 93 => r"\biguplus",
        86 | 94 => r"\bigwedge",
        87 | 95 => r"\bigvee",
        96 | 97 => r"\coprod",
        98..=100 => "ACC:widehat",
        101..=103 => "ACC:widetilde",
        112..=116 => "SQRT",
        _ => return None,
    })
}

/// cmmi non-letters.
fn oml(code: u32) -> Option<&'static str> {
    const GREEK: [&str; 40] = [
        r"\Gamma",
        r"\Delta",
        r"\Theta",
        r"\Lambda",
        r"\Xi",
        r"\Pi",
        r"\Sigma",
        r"\Upsilon",
        r"\Phi",
        r"\Psi",
        r"\Omega",
        r"\alpha",
        r"\beta",
        r"\gamma",
        r"\delta",
        r"\epsilon",
        r"\zeta",
        r"\eta",
        r"\theta",
        r"\iota",
        r"\kappa",
        r"\lambda",
        r"\mu",
        r"\nu",
        r"\xi",
        r"\pi",
        r"\rho",
        r"\sigma",
        r"\tau",
        r"\upsilon",
        r"\phi",
        r"\chi",
        r"\psi",
        r"\omega",
        r"\varepsilon",
        r"\vartheta",
        r"\varpi",
        r"\varrho",
        r"\varsigma",
        r"\varphi",
    ];
    if (code as usize) < GREEK.len() {
        return Some(GREEK[code as usize]);
    }
    Some(match code {
        58 => ".",
        59 => ",",
        60 => "<",
        61 => "/",
        62 => ">",
        63 => r"\star",
        64 => r"\partial",
        91 => r"\flat",
        92 => r"\natural",
        93 => r"\sharp",
        96 => r"\ell",
        123 => r"\imath",
        124 => r"\jmath",
        125 => r"\wp",
        126 => "ACC:vec",
        _ => return None,
    })
}

fn msam(code: u32) -> Option<&'static str> {
    Some(match code {
        3 => r"\square",
        4 => r"\blacksquare",
        6 => r"\Diamond",
        54 | 44 => r"\leqslant",
        62 => r"\geqslant",
        38 => r"\gtrsim",
        45 => r"\eqslantless",
        46 => r"\lesssim",
        _ => return None,
    })
}

/// LaTeX for the raw char code of a glyph PDFium gave no Unicode for, in a
/// font following `enc`; None when the encoding has no entry.
pub(crate) fn decode(enc: Enc, code: u32) -> Option<&'static str> {
    match enc {
        Enc::Oms => oms(code),
        Enc::Omx => omx(code),
        Enc::Oml => oml(code),
        Enc::Msam => msam(code),
    }
}
