//! Preset pattern fills (`a:pattFill prst="…"`) as 8×8 one-bit tiles.
//!
//! PowerPoint draws a pattern tile at screen-pixel scale: 8 pixels at 96 dpi, i.e. 6 pt,
//! anchored to the slide (measured on its slide thumbnails). The percentage presets are
//! ordered-dither masks with exactly that share of foreground pixels; the others are
//! drawn after each preset's name and its look in Office (no open bitmap set exists).
//! Row `r`, bit `0x80 >> x` set means pixel (x, r) takes the foreground colour.

/// Points per pattern pixel (one screen pixel at 96 dpi).
pub const PIXEL_PT: f32 = 0.75;

/// The tile for `preset`; unknown names get a 50% mix so the fill keeps its tone.
pub fn tile(preset: &str) -> [u8; 8] {
    if let Some(pct) = preset
        .strip_prefix("pct")
        .and_then(|p| p.parse::<u32>().ok())
    {
        return dither(pct.min(100));
    }
    let rows: [u8; 8] = match preset {
        "horz" => [0xFF, 0, 0, 0, 0, 0, 0, 0],
        "vert" => [0x80; 8],
        "ltHorz" => [0xFF, 0, 0, 0, 0xFF, 0, 0, 0],
        "ltVert" => [0x88; 8],
        "dkHorz" => [0xFF, 0xFF, 0, 0, 0xFF, 0xFF, 0, 0],
        "dkVert" => [0xCC; 8],
        "narHorz" => [0xFF, 0, 0xFF, 0, 0xFF, 0, 0xFF, 0],
        "narVert" => [0xAA; 8],
        "dashHorz" => [0xF0, 0, 0, 0, 0x0F, 0, 0, 0],
        "dashVert" => [0x80, 0x80, 0x80, 0x80, 0x08, 0x08, 0x08, 0x08],
        "cross" | "lgGrid" => [0xFF, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80],
        "smGrid" => [0xFF, 0x88, 0x88, 0x88, 0xFF, 0x88, 0x88, 0x88],
        "dotGrid" => [0xAA, 0, 0x80, 0, 0x80, 0, 0x80, 0],
        "dnDiag" => [0x80, 0x40, 0x20, 0x10, 0x08, 0x04, 0x02, 0x01],
        "upDiag" => [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80],
        "ltDnDiag" => [0x88, 0x44, 0x22, 0x11, 0x88, 0x44, 0x22, 0x11],
        "ltUpDiag" => [0x11, 0x22, 0x44, 0x88, 0x11, 0x22, 0x44, 0x88],
        "dkDnDiag" => [0xCC, 0x66, 0x33, 0x99, 0xCC, 0x66, 0x33, 0x99],
        "dkUpDiag" => [0x33, 0x66, 0xCC, 0x99, 0x33, 0x66, 0xCC, 0x99],
        "wdDnDiag" => [0xE0, 0x70, 0x38, 0x1C, 0x0E, 0x07, 0x83, 0xC1],
        "wdUpDiag" => [0x07, 0x0E, 0x1C, 0x38, 0x70, 0xE0, 0xC1, 0x83],
        "dashDnDiag" => [0x88, 0x44, 0, 0, 0x88, 0x44, 0, 0],
        "dashUpDiag" => [0x11, 0x22, 0, 0, 0x11, 0x22, 0, 0],
        "diagCross" => [0x81, 0x42, 0x24, 0x18, 0x18, 0x24, 0x42, 0x81],
        "smCheck" => [0xCC, 0xCC, 0x33, 0x33, 0xCC, 0xCC, 0x33, 0x33],
        "lgCheck" => [0xF0, 0xF0, 0xF0, 0xF0, 0x0F, 0x0F, 0x0F, 0x0F],
        "smConfetti" => [0x80, 0x04, 0x40, 0x02, 0x08, 0x01, 0x20, 0x10],
        "lgConfetti" => [0xC0, 0xC6, 0x06, 0x30, 0x33, 0x03, 0x60, 0x6C],
        "horzBrick" => [0xFF, 0x80, 0x80, 0x80, 0xFF, 0x08, 0x08, 0x08],
        "diagBrick" => [0x01, 0x02, 0x04, 0x08, 0x18, 0x24, 0x42, 0x81],
        "solidDmnd" => [0x10, 0x38, 0x7C, 0xFE, 0x7C, 0x38, 0x10, 0x00],
        "openDmnd" => [0x10, 0x28, 0x44, 0x82, 0x44, 0x28, 0x10, 0x00],
        "dotDmnd" => [0x80, 0x00, 0x22, 0x00, 0x08, 0x00, 0x22, 0x00],
        "plaid" => [0xAA, 0x55, 0xAA, 0x55, 0xF0, 0xF0, 0xF0, 0xF0],
        "sphere" => [0x77, 0x98, 0xF8, 0xF8, 0x77, 0x89, 0x8F, 0x8F],
        "weave" => [0x88, 0x54, 0x22, 0x45, 0x88, 0x14, 0x22, 0x51],
        "divot" => [0x00, 0x10, 0x08, 0x10, 0x00, 0x01, 0x80, 0x01],
        "shingle" => [0x03, 0x84, 0x48, 0x30, 0x0C, 0x02, 0x01, 0x01],
        "wave" => [0x00, 0x18, 0xA4, 0x03, 0x00, 0x18, 0xA4, 0x03],
        "trellis" => [0xFF, 0x66, 0xFF, 0x99, 0xFF, 0x66, 0xFF, 0x99],
        "zigZag" => [0x81, 0x42, 0x24, 0x18, 0x81, 0x42, 0x24, 0x18],
        _ => return dither(50),
    };
    rows
}

/// An 8×8 Bayer ordered-dither mask with `pct`% of its pixels set.
fn dither(pct: u32) -> [u8; 8] {
    const BAYER: [[u8; 8]; 8] = [
        [0, 32, 8, 40, 2, 34, 10, 42],
        [48, 16, 56, 24, 50, 18, 58, 26],
        [12, 44, 4, 36, 14, 46, 6, 38],
        [60, 28, 52, 20, 62, 30, 54, 22],
        [3, 35, 11, 43, 1, 33, 9, 41],
        [51, 19, 59, 27, 49, 17, 57, 25],
        [15, 47, 7, 39, 13, 45, 5, 37],
        [63, 31, 55, 23, 61, 29, 53, 21],
    ];
    let on = (pct * 64 + 50) / 100;
    let mut rows = [0u8; 8];
    for (y, row) in BAYER.iter().enumerate() {
        for (x, &rank) in row.iter().enumerate() {
            if u32::from(rank) < on {
                rows[y] |= 0x80 >> x;
            }
        }
    }
    rows
}

