/// A proprietary symbol font with a byte → Unicode table.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SymbolFont {
    Symbol,
    Wingdings,
    Wingdings2,
    Wingdings3,
    Webdings,
}

impl SymbolFont {
    /// Recognizes a family name, ignoring case, spaces, hyphens and
    /// underscores, so "Wingdings 2", "Wingdings2" and "WINGDINGS-2" all
    /// match. PostScript names (`SymbolMT`, `Wingdings-Regular`) also match, and so
    /// does the first entry of a fallback list ("Wingdings,Sans-Serif").
    pub fn from_name(name: &str) -> Option<Self> {
        let key: String = first_family(name)
            .chars()
            .filter(|c| !matches!(c, ' ' | '-' | '_'))
            .flat_map(char::to_lowercase)
            .collect();
        let key = key.strip_suffix("regular").unwrap_or(&key);
        Some(match key {
            "symbol" | "symbolmt" => SymbolFont::Symbol,
            "wingdings" => SymbolFont::Wingdings,
            "wingdings2" => SymbolFont::Wingdings2,
            "wingdings3" => SymbolFont::Wingdings3,
            "webdings" => SymbolFont::Webdings,
            _ => return None,
        })
    }

    fn table(self) -> &'static [char; 224] {
        match self {
            SymbolFont::Symbol => &SYMBOL,
            SymbolFont::Wingdings => &WINGDINGS,
            SymbolFont::Wingdings2 => &WINGDINGS_2,
            SymbolFont::Wingdings3 => &WINGDINGS_3,
            SymbolFont::Webdings => &WEBDINGS,
        }
    }

    /// The Unicode equivalent of `ch` in this font. Characters outside the
    /// byte range (0x20–0xFF or U+F020–U+F0FF) are returned unchanged:
    /// PowerPoint draws real Unicode text in a symbol-font run with a
    /// fallback font.
    pub fn map(self, ch: char) -> char {
        match symbol_code(ch) {
            Some(code) => self.table()[(code - 0x20) as usize],
            None => ch,
        }
    }

    /// The real font's advance width for `ch` (in em), so a mapped glyph drawn
    /// with another face still takes the room PowerPoint gives it (bullet indents
    /// depend on it). `None` for Symbol and for codes the font leaves empty.
    pub fn advance_em(self, ch: char) -> Option<f64> {
        let widths = match self {
            SymbolFont::Wingdings => &WINGDINGS_WIDTHS,
            SymbolFont::Wingdings2 => &WINGDINGS_2_WIDTHS,
            SymbolFont::Wingdings3 => &WINGDINGS_3_WIDTHS,
            SymbolFont::Webdings => &WEBDINGS_WIDTHS,
            SymbolFont::Symbol => return None,
        };
        let w = widths[(symbol_code(ch)? - 0x20) as usize];
        (w > 0).then_some(w as f64 / 1000.0)
    }
}

/// The byte a symbol font sees for `ch`, when it is in the printable range.
fn symbol_code(ch: char) -> Option<u32> {
    let c = ch as u32;
    let code = if (0xF020..=0xF0FF).contains(&c) {
        c - 0xF000
    } else {
        c
    };
    (0x20..=0xFF).contains(&code).then_some(code)
}

/// Maps `ch` set in `font` to Unicode, or `None` when `font` is not a symbol
/// font. Other dingbat fonts without a table here draw every byte code as a
/// bullet.
pub fn map_symbol_char(font: &str, ch: char) -> Option<char> {
    if let Some(sf) = SymbolFont::from_name(font) {
        return Some(sf.map(ch));
    }
    match first_family(font).to_lowercase().as_str() {
        "marlett" | "monotype sorts" | "zapfdingbats" => {
            Some(if symbol_code(ch).is_some() { '•' } else { ch })
        }
        _ => None,
    }
}

/// The first family of a comma-separated list, as PDF converters write
/// `typeface="Wingdings,Sans-Serif"`.
fn first_family(name: &str) -> &str {
    name.split(',')
        .next()
        .unwrap_or(name)
        .trim()
        .trim_matches('"')
}

