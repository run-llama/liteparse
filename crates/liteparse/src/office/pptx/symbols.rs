//! Unicode equivalents for the Microsoft symbol fonts: Symbol, Wingdings,
//! Wingdings 2, Wingdings 3 and Webdings.
//!
//! These fonts are proprietary and never installed where office::pptx runs, so
//! text set in them is remapped to Unicode and drawn with open fonts (mostly
//! Noto Sans Symbols 2, which was designed to cover this repertoire). The
//! mapped character is also what text extraction reports.
//!
//! A symbol font addresses its glyphs by byte value. Decks store the byte
//! either as the Latin-1 character (`§` = 0xA7) or as the private-use form
//! U+F0xx that Windows exposes for symbol-encoded fonts; both are accepted.
//!
//! Sources (mappings are facts; no third-party code or data files are used):
//! - Wingdings, Wingdings 2, Wingdings 3, Webdings: the source-reference table
//!   in "Status of encoding of Wingdings and Webdings Symbols", ISO/IEC JTC1/SC2/WG2
//!   N4384 = UTC L2/12-368 (M. Suignard, 2012), the document behind the
//!   Unicode 7.0 additions. Every code point was checked against the Unicode
//!   character database.
//! - Symbol: the Unicode Consortium's "Adobe Symbol Encoding to Unicode" table
//!   (`Public/MAPPINGS/VENDORS/ADOBE/symbol.txt`).
//!
//! Deliberate deviations from those tables:
//! - Symbol's corporate-use code points (bracket and integral pieces, arrow and
//!   radical extenders, serif/sans ® © ™) use the standard pieces U+239B–U+23AE,
//!   U+23D0, U+203E and ® © ™. The horizontal arrow extender 0xBE keeps
//!   an em dash, which is how it is used in running text.
//! - Where the Adobe table lists two characters, the Greek letter wins
//!   (Δ, Ω, μ) and 0xA4 is U+2044 FRACTION SLASH.
//! - Wingdings 0x6C is U+25CF ● rather than U+26AB ⚫: the latter has emoji
//!   presentation by default, a poor fit for the most common round bullet.
//! - Wingdings 0xFF (the Windows logo) was not encoded; U+229E ⊞ stands in.
//! - Codes with no glyph in the original font (0x7F everywhere; Symbol
//!   0x80–0x9F, 0xF0, 0xFF; Wingdings 2 0xFA–0xFF; Wingdings 3 0xF1–0xFF) map
//!   to a space.

