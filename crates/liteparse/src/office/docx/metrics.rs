/// Monospaced East Asian fonts: half-width Latin, full-width ideographs.
/// The family a `_GB2312` name (仿宋_GB2312, KaiTi_GB2312: the Windows XP builds of
/// the GB fonts) shares its metrics with.
/// Whether a family name carries a `_GBK` suffix (Founder's GBK faces): Word for
/// Mac draws a missing one with Microsoft YaHei even under a GB2312 charset, where a
/// missing `方正…简体` draws with SimHei (Word's PDFs of the source files).
fn gbk_name(family: &str) -> bool {
    family.trim().to_lowercase().ends_with("_gbk")
}

fn gb2312_base(family: &str) -> &str {
    let f = family.trim();
    f.strip_suffix("_GB2312")
        .or_else(|| f.strip_suffix("_gb2312"))
        .unwrap_or(f)
}

