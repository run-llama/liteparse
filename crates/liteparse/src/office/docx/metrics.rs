/// A single full-width CJK punctuation mark: `Some(true)` for opening marks
/// (their blank half is on the left), `Some(false)` for the others.
pub fn compressible_punct(piece: &str) -> Option<bool> {
    let mut it = piece.chars();
    let c = it.next()?;
    if it.next().is_some() {
        return None;
    }
    match c {
        '\u{3008}' | '\u{300A}' | '\u{300C}' | '\u{300E}' | '\u{3010}' | '\u{3014}'
        | '\u{3016}' | '\u{FF08}' | '\u{FF3B}' | '\u{FF5B}' => Some(true),
        '\u{3001}' | '\u{3002}' | '\u{3009}' | '\u{300B}' | '\u{300D}' | '\u{300F}'
        | '\u{3011}' | '\u{3015}' | '\u{3017}' | '\u{FF09}' | '\u{FF0C}' | '\u{FF0E}'
        | '\u{FF1A}' | '\u{FF1B}' | '\u{FF01}' | '\u{FF1F}' | '\u{FF3D}' | '\u{FF5D}' => {
            Some(false)
        }
        _ => None,
    }
}

/// fontTable.xml facts for families Word could not find: (altName, family
/// class `roman`/`swiss`/..., charset), keyed by lowercase family name.
type FontTableMap =
    std::collections::HashMap<String, (Option<String>, Option<String>, Option<String>)>;

static FONT_TABLE: std::sync::OnceLock<std::sync::Mutex<FontTableMap>> = std::sync::OnceLock::new();

fn font_table() -> &'static std::sync::Mutex<FontTableMap> {
    FONT_TABLE.get_or_init(Default::default)
}

/// Serializes tests around the process-global font table: `cargo test` runs
/// tests in parallel, so hold this from `set_font_table` through the last read
/// of the table. `extract::open` takes it too while it fills the table.
#[cfg(test)]
pub(crate) static FONT_TABLE_TEST_LOCK: std::sync::Mutex<()> = std::sync::Mutex::new(());

/// Records the document's font table (`word/fontTable.xml`).
pub fn set_font_table(root: Option<&crate::office::pptx::xml::XNode>) {
    let mut map = font_table().lock().unwrap_or_else(|p| p.into_inner());
    map.clear();
    let Some(root) = root else { return };
    for f in root.children_named("w:font") {
        let Some(name) = f.attr("name") else { continue };
        let alt = f
            .child("w:altName")
            .and_then(|a| a.attr("val"))
            .map(str::to_string)
            .filter(|a| !a.trim().is_empty());
        let class = f
            .child("w:family")
            .and_then(|a| a.attr("val"))
            .map(str::to_string);
        let charset = f
            .child("w:charset")
            .and_then(|a| a.attr("val"))
            .map(|v| v.trim().to_ascii_lowercase());
        map.insert(name.trim().to_lowercase(), (alt, class, charset));
    }
}

/// The family Word actually used for `family`. A family that is neither
/// installed, nor substitutable, nor tabled takes the font table's `altName`
/// (what Word recorded it fell back to; `Serif` → Times New Roman on a page-1
/// thumbnail). Mapping by family class (roman → Times New Roman...) lost its
/// A/B and is not done.
pub fn effective_family(fonts: &FontSystem, family: &str) -> String {
    let key = family.trim().to_lowercase();
    let known = |f: &str| {
        fonts.has_family(f)
            || crate::office::pptx::fonts::has_substitute(f)
            || fonts.has_user_substitute(f)
            || word_face(fonts, f, false, false).is_some()
            || OFFICE_METRICS
                .iter()
                .any(|m| m.0 == f.trim().to_lowercase())
    };
    // Word for Mac has no Noto fonts: one that Google Docs wrote (bullets in
    // "Noto Sans Symbols") draws with the font table's altName even where we have
    // the font (a form's ● bullets in Word's PDF: Calibri, Calibri line height).
    let word_lacks = key.starts_with("noto ");
    // A PostScript-style name ("Arial-BoldMT", "Palatino-Roman", "TimesNewRomanPSMT")
    // is no family name to Word, which draws the font table's altName (a form's
    // "Arial-BoldMT" footer in Malgun Gothic Semilight, Word's PDF).
    let postscript = !key.contains(' ') && (key.contains('-') || key.ends_with("mt"));
    if postscript {
        let map = font_table().lock().unwrap_or_else(|p| p.into_inner());
        if let Some(alt) = map.get(&key).and_then(|(alt, ..)| alt.as_deref()) {
            // Semilight shares Malgun Gothic's metrics; only its strokes are lighter.
            let alt = if alt.eq_ignore_ascii_case("malgun gothic semilight") {
                "Malgun Gothic"
            } else {
                alt
            };
            if known(alt) {
                return alt.to_string();
            }
        }
    }
    if key.is_empty() || (known(family) && !word_lacks) {
        return family.to_string();
    }
    // Word for Mac draws a missing Myriad Pro with Segoe UI (a specification sheet's
    // body text: Segoe UI in Word's PDF).
    if key.starts_with("myriad pro") && known("Segoe UI") {
        return "Segoe UI".to_string();
    }
    let map = font_table().lock().unwrap_or_else(|p| p.into_inner());
    match map.get(&key).and_then(|(alt, ..)| alt.as_deref()) {
        Some(a) if known(a) => a.to_string(),
        // Without an altName, a Noto font Word lacks draws with Arial (Google Docs
        // "Noto Sans Symbols" bullets in Word's PDF: ArialMT, body line height).
        _ if word_lacks && known("Arial") => "Arial".to_string(),
        _ => {
            // Word for Mac draws a missing font named in ideographs (plus a `_GB2312` or
            // `_GBK` suffix) with Microsoft YaHei, Latin included (14 pt 幼圆 underscores
            // advance 6.28 pt), unless a GB2312 charset marks a non-GBK face (SimHei, see
            // east_asian_em). Kana or Latin letters mark a font Word substitutes otherwise.
            let name = gb2312_base(family).trim();
            let name = name.strip_suffix("_GBK").unwrap_or(name);
            let chinese =
                !name.is_empty() && name.chars().all(|c| ('\u{4E00}'..='\u{9FFF}').contains(&c));
            let gb2312 = !gbk_name(family)
                && map
                    .get(&key)
                    .is_some_and(|(.., cs)| cs.as_deref() == Some("86"));
            if chinese && !gb2312 && known("Microsoft YaHei") {
                "Microsoft YaHei".to_string()
            } else {
                family.to_string()
            }
        }
    }
}
