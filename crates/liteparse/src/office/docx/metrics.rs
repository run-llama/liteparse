/// Numeric metrics of a Microsoft font with no metric-compatible open clone
/// (`word_tables.rs`, generated by `scripts/gen_word_metrics.py`). Layout takes
/// line heights, advances and kerning from it; glyphs come from a substitute.
pub struct WordFace {
    pub family: &'static str,
    /// Other names of the family (localized name records, e.g. ＭＳ ゴシック).
    pub aliases: &'static [&'static str],
    pub bold: bool,
    pub italic: bool,
    /// OS/2 `USE_TYPO_METRICS`: Word sizes lines from the typo metrics.
    pub use_typo: bool,
    pub upm: u16,
    pub win_ascent: u16,
    pub win_descent: u16,
    /// (ascender, descender, line gap).
    pub hhea: (i16, i16, i16),
    pub typo: (i16, i16, i16),
    /// (position, thickness).
    pub underline: (i16, i16),
    pub strikeout: (i16, i16),
    /// Advance widths in font units for runs of consecutive codepoints.
    pub advances: &'static [(u32, &'static [u16])],
    /// Kerning pairs (first, second, adjustment in font units), sorted.
    pub kern: &'static [(u32, u32, i16)],
}

impl WordFace {
    pub fn advance(&self, ch: char) -> Option<u16> {
        let c = ch as u32;
        let i = self.advances.partition_point(|(start, _)| *start <= c);
        let (start, run) = self.advances.get(i.checked_sub(1)?)?;
        run.get((c - start) as usize).copied()
    }

    pub fn kerning(&self, a: char, b: char) -> i16 {
        let key = (a as u32, b as u32);
        self.kern
            .binary_search_by(|(x, y, _)| (*x, *y).cmp(&key))
            .map_or(0, |i| self.kern[i].2)
    }

    /// GDI line metrics in font units: (ascent with external leading, descent).
    fn gdi(&self) -> (f64, f64) {
        // The legacy Thai faces space lines by their hhea metrics in Word for Mac
        // (14 pt Cordia New: 16 pt lines, 1.147 em; its win metrics give 1.386 em).
        if matches!(
            self.family,
            "Angsana New" | "Cordia New" | "AngsanaUPC" | "CordiaUPC" | "Browallia New"
        ) {
            let (a, d, gap) = self.hhea;
            return (a as f64 + gap.max(0) as f64, -(d as f64));
        }
        if self.use_typo {
            let (a, d, gap) = self.typo;
            return (a as f64 + gap.max(0) as f64, -(d as f64));
        }
        let win = self.win_ascent as f64 + self.win_descent as f64;
        let hh = self.hhea.0 as f64 - self.hhea.1 as f64;
        let ext = (self.hhea.2 as f64 - (win - hh)).max(0.0);
        // A face whose hhea box is shorter than its win box spaces by hhea too (Word
        // for Mac: 12 pt Book Antiqua at 1.5 lines is 21.7 pt, 1.206 em, not 1.243),
        // unless the box is a legacy 1 em one (Baskerville Old Face lines are win's).
        let (a, d, gap) = self.hhea;
        let hh_line = a as f64 - d as f64 + gap.max(0) as f64;
        if hh_line < win + ext - 1.0 && hh_line >= 1.1 * self.upm as f64 {
            return (a as f64 + gap.max(0) as f64, -(d as f64));
        }
        (self.win_ascent as f64 + ext, self.win_descent as f64)
    }
}

static WORD_METRICS: std::sync::atomic::AtomicBool = std::sync::atomic::AtomicBool::new(true);

/// Turns the Microsoft metrics tables on or off (`render.wordMetrics`).
pub fn set_word_metrics(on: bool) {
    WORD_METRICS.store(on, std::sync::atomic::Ordering::Relaxed);
}

/// The metrics table for a requested family and style, when the family is not
/// installed as a real font. A missing style takes the closest one present.
pub fn word_face(
    fonts: &FontSystem,
    family: &str,
    bold: bool,
    italic: bool,
) -> Option<&'static WordFace> {
    word_face_table(family, bold, italic).filter(|_| !fonts.has_family(gb2312_base(family)))
}

/// The Microsoft metrics table for `family`, whether or not the font is installed.
/// Line heights use it even for an installed face: Word sizes lines with GDI's
/// metrics, which a face file's own tables can disagree with.
pub fn word_face_table(family: &str, bold: bool, italic: bool) -> Option<&'static WordFace> {
    if !WORD_METRICS.load(std::sync::atomic::Ordering::Relaxed) {
        return None;
    }
    let name = gb2312_base(family);
    let mut best: Option<(&'static WordFace, u8)> = None;
    let faces: &[WordFace] = word_tables::FACES;
    let named = |f: &&WordFace| {
        f.family.eq_ignore_ascii_case(name)
            || f.aliases.iter().any(|a| a.eq_ignore_ascii_case(name))
    };
    for f in faces.iter().filter(named) {
        let score = (f.bold == bold) as u8 * 2 + (f.italic == italic) as u8;
        if best.is_none_or(|(_, s)| score > s) {
            best = Some((f, score));
        }
    }
    best.map(|(face, _)| face)
}

/// Whether `family` has tabled Office metrics (symbol fonts among them).
pub fn office_tabled(family: &str) -> bool {
    let key = family.trim().to_lowercase();
    OFFICE_METRICS.iter().any(|m| m.0 == key)
}

/// Ascent and descent (points) of a single line of `family` at `size`. The
/// external leading is counted in the ascent: Word puts it above the text.
#[cfg(test)]
pub fn line_metrics(
    fonts: &FontSystem,
    family: &str,
    face: Option<fontdb::ID>,
    size: f64,
) -> (f64, f64) {
    line_metrics_styled(fonts, family, face, size, false, false)
}

/// Requested run style stays explicit when a substitute lacks a matching face.
pub fn line_metrics_styled(
    fonts: &FontSystem,
    family: &str,
    face: Option<fontdb::ID>,
    size: f64,
    _bold: bool,
    _italic: bool,
) -> (f64, f64) {
    let (a, d) = base_line_metrics(fonts, family, face, size);
    // Word spaces a single line of an East Asian font at 1.3 times the font's Windows
    // line height (win ascent + descent, no gap): Word for Mac probes at 9-20 pt give
    // SimSun 1.30 em, YaHei 1.71 em, Meiryo 1.94 em (A/B vs Word: 399 DOCX visual
    // 0.788 -> 0.796, 588 DOC 0.756 -> 0.758).
    if let Some(em) = east_asian_em(fonts, family, face) {
        let total = 1.3 * em * size;
        // The font's own line (em) keeps its ascent:descent proportion; Word puts 45%
        // of the 1.3 rule's extra below the baseline (probes, baseline steps between
        // Times New Roman and PMingLiU, SimSun, YaHei lines: within 0.1 pt).
        let natural = if a + d > 0.0 {
            d / (a + d) * em * size
        } else {
            0.0
        };
        let desc = (natural + 0.45 * (total - em * size)).min(total);
        return (total - desc, desc);
    }
    (a, d)
}

/// Height a run of `family` gains from the East Asian 1.3 rule (points; 0 for other
/// families). Lines that snap to a document grid take it back off: Word snaps the
/// font's plain height.
pub fn east_asian_extra(
    fonts: &FontSystem,
    family: &str,
    face: Option<fontdb::ID>,
    size: f64,
) -> f64 {
    let Some(em) = east_asian_em(fonts, family, face) else {
        return 0.0;
    };
    // The extra over the font's own Windows line height (em), which a substitute
    // face's metrics would misstate (a missing Founder font at 1.0 em drawn with a
    // 1.44 em face: Word snaps 48 pt to four 15.6 pt pitches, not five).
    let (a, d) = line_metrics_styled(fonts, family, face, size, false, false);
    (a + d) - em * size
}

/// Windows line height (em) of an East Asian family: a table for the common ones
/// (measured, as Word's line height / 1.3), else the OS/2 win metrics of a real face
/// whose code pages cover Japanese, Chinese or Korean. `None` for other families.
fn east_asian_em(fonts: &FontSystem, family: &str, face: Option<fontdb::ID>) -> Option<f64> {
    let f = gb2312_base(family).trim().to_lowercase();
    let known = match f.as_str() {
        "microsoft yahei" | "微软雅黑" | "microsoft yahei ui" => Some(1.32),
        "microsoft jhenghei" | "微軟正黑體" | "microsoft jhenghei ui" => Some(1.33),
        "malgun gothic" | "맑은 고딕" => Some(1.33),
        "meiryo" | "メイリオ" | "meiryo ui" => Some(1.5),
        "yu gothic" | "游ゴシック" | "yu mincho" | "游明朝" | "yu gothic ui" => Some(1.1),
        "dengxian" | "等线" => Some(1.04),
        "ms pgothic"
        | "ｍｓ ｐゴシック"
        | "ms pmincho"
        | "ｍｓ ｐ明朝"
        | "ms ui gothic"
        | "pmingliu"
        | "新細明體"
        | "mingliu_hkscs"
        | "batang"
        | "바탕"
        | "gulim"
        | "굴림"
        | "dotum"
        | "돋움"
        | "gungsuh"
        | "궁서"
        | "simkai"
        | "stsong"
        | "stkaiti"
        | "stfangsong"
        | "stheiti" => Some(1.0),
        // Word for Mac has no DFKai-SB and draws it with Microsoft YaHei, taking
        // YaHei's line height (18 pt probe: 30.9 pt = 1.3 x 1.32 em).
        "dfkai-sb" | "標楷體" if !real_face(fonts, face, &["dfkai", "標楷"]) => Some(1.32),
        n if mono_cjk(n) => Some(1.0),
        // A missing Founder (FZ) family: a GB2312 (charset 86) font-table entry falls
        // back to SimHei (1 em), any other to Microsoft YaHei. Real FZ faces (embedded
        // or installed) keep their own metrics below.
        n if (n.starts_with("方正") || n.starts_with("fz"))
            && !real_face(fonts, face, &["方正", "fz"]) =>
        {
            let map = font_table().lock().unwrap_or_else(|p| p.into_inner());
            let gb2312 = map
                .get(n)
                .is_some_and(|(.., cs)| cs.as_deref() == Some("86"));
            Some(if gb2312 && !gbk_name(n) { 1.0 } else { 1.32 })
        }
        _ => None,
    };
    if known.is_some() {
        return known;
    }
    // A real CJK face (not a substitute for some other family).
    let fd = face.and_then(|id| fonts.face(id))?;
    if !fd.family.eq_ignore_ascii_case(family.trim()) {
        return None;
    }
    let cjk = code_pages(&fd).is_some_and(|cp| cp & (0b1_1111 << 17) != 0);
    let t = ttf_parser_face(&fd)?;
    let os2 = t.tables().os2?;
    let win = os2.windows_ascender() as f64 + os2.windows_descender().unsigned_abs() as f64;
    let upm = fd.metrics.units_per_em as f64;
    (cjk && upm > 0.0 && win > 0.0).then(|| win / upm)
}

/// Whether the resolved face is the family itself (its lowercase name starts with
/// one of `prefixes`), as opposed to a substitute.
fn real_face(fonts: &FontSystem, face: Option<fontdb::ID>, prefixes: &[&str]) -> bool {
    face.and_then(|id| fonts.face(id)).is_some_and(|fd| {
        let real = fd.family.to_lowercase();
        prefixes.iter().any(|p| real.starts_with(p))
    })
}

/// OS/2 ulCodePageRange1 of a face (bits 17-21: Japanese, Chinese simplified, Korean
/// Wansung, Chinese traditional, Korean Johab).
fn code_pages(fd: &crate::office::pptx::fonts::FaceData) -> Option<u32> {
    let face = ttf_parser_face(fd)?;
    let os2 = face
        .raw_face()
        .table(rustybuzz::ttf_parser::Tag::from_bytes(b"OS/2"))?;
    let version = u16::from_be_bytes([*os2.first()?, *os2.get(1)?]);
    if version < 1 {
        return None;
    }
    let b = os2.get(78..82)?;
    Some(u32::from_be_bytes([b[0], b[1], b[2], b[3]]))
}

fn base_line_metrics(
    fonts: &FontSystem,
    family: &str,
    face: Option<fontdb::ID>,
    size: f64,
) -> (f64, f64) {
    let key = family.trim().to_lowercase();

    if let Some(wf) = word_face_table(family, false, false) {
        let (a, d) = wf.gdi();
        let upm = wf.upm as f64;
        return (a / upm * size, d / upm * size);
    }
    if let Some((_, upm, asc, desc, ext)) = OFFICE_METRICS.iter().find(|m| m.0 == key) {
        return ((asc + ext) / upm * size, desc / upm * size);
    }
    if let Some(fd) = face.and_then(|id| fonts.face(id)) {
        let base = crate::office::pptx::fonts::normalize_family(family).0;
        let substituted = !fd.family.eq_ignore_ascii_case(family.trim())
            && !fd.family.eq_ignore_ascii_case(base.trim());
        let scale = if substituted {
            fonts.em_scale(family, face.unwrap())
        } else {
            1.0
        };
        if let Some(metrics) = face_line_metrics(&fd, size, substituted, scale) {
            return metrics;
        }
    }
    (0.905 * size, 0.212 * size)
}

/// External leading (points) that `base_line_metrics` adds above the ascent; Word
/// leaves it out under `w:noLeading`. 0 for East Asian families (1.3 rule).
pub fn external_leading(
    fonts: &FontSystem,
    family: &str,
    face: Option<fontdb::ID>,
    size: f64,
) -> f64 {
    if east_asian_em(fonts, family, face).is_some() {
        return 0.0;
    }
    let key = family.trim().to_lowercase();
    if let Some(wf) = word_face_table(family, false, false) {
        let upm = wf.upm as f64;
        let ext = if wf.use_typo {
            wf.typo.2.max(0) as f64
        } else {
            (wf.gdi().0 - wf.win_ascent as f64).max(0.0)
        };
        return ext / upm * size;
    }
    if let Some((_, upm, _, _, ext)) = OFFICE_METRICS.iter().find(|m| m.0 == key) {
        return ext / upm * size;
    }
    face.and_then(|id| fonts.face(id))
        .filter(|fd| fd.family.eq_ignore_ascii_case(family.trim()))
        .and_then(|fd| {
            let upm = fd.metrics.units_per_em as f64;
            gdi_external_leading(&fd).map(|e| e / upm * size)
        })
        .unwrap_or(0.0)
}

/// Line metrics of a verified source face, without requested-family tables.
pub fn source_line_metrics(fonts: &FontSystem, id: fontdb::ID, size: f64) -> (f64, f64) {
    fonts
        .face(id)
        .and_then(|fd| face_line_metrics(&fd, size, false, 1.0))
        .unwrap_or((0.905 * size, 0.212 * size))
}

fn face_line_metrics(
    fd: &crate::office::pptx::fonts::FaceData,
    size: f64,
    substituted: bool,
    scale: f64,
) -> Option<(f64, f64)> {
    let upm = fd.metrics.units_per_em as f64;
    if upm <= 0.0 {
        return None;
    }
    if !substituted
        && let Some((a, d)) = typo_metrics(fd)
        && a + d > 0.0
    {
        return Some((a / upm * size, d / upm * size));
    }
    let ext = if substituted {
        0.0
    } else {
        gdi_external_leading(fd).unwrap_or(0.0)
    };
    let asc = fd.metrics.ascent as f64 + ext;
    let desc = fd.metrics.descent as f64;
    // An installed face with a shorter hhea box (of at least 1.1 em) spaces by it, as
    // tabled ones do (Word for Mac: 10 pt Roboto lines 11.76 pt, not 12 by win).
    if !substituted && let Some(hhea) = ttf_parser_face(fd).map(|f| f.tables().hhea) {
        let gap = hhea.line_gap.max(0) as f64;
        let hh = hhea.ascender as f64 - hhea.descender as f64 + gap;
        if hh < asc + desc - 1.0 && hh >= 1.1 * upm {
            let a = hhea.ascender as f64 + gap;
            let d = -(hhea.descender as f64);
            return Some((a / upm * size * scale, d / upm * size * scale));
        }
    }
    (asc + desc > 0.0).then_some((asc / upm * size * scale, desc / upm * size * scale))
}

/// Typo ascent (plus line gap) and descent of a face flagged USE_TYPO_METRICS.
fn typo_metrics(fd: &crate::office::pptx::fonts::FaceData) -> Option<(f64, f64)> {
    let face = ttf_parser_face(fd)?;
    let os2 = face.tables().os2?;
    if !os2.use_typographic_metrics() {
        return None;
    }
    let gap = os2.typographic_line_gap().max(0) as f64;
    Some((
        os2.typographic_ascender() as f64 + gap,
        -(os2.typographic_descender() as f64),
    ))
}

/// GDI's `tmExternalLeading` of a face, in font units.
fn gdi_external_leading(fd: &crate::office::pptx::fonts::FaceData) -> Option<f64> {
    let face = ttf_parser_face(fd)?;
    let os2 = face.tables().os2?;
    let hhea = face.tables().hhea;
    let win = os2.windows_ascender() as f64 + os2.windows_descender().unsigned_abs() as f64;
    let hh = hhea.ascender as f64 - hhea.descender as f64;
    Some((hhea.line_gap as f64 - (win - hh)).max(0.0))
}

fn ttf_parser_face(
    fd: &crate::office::pptx::fonts::FaceData,
) -> Option<rustybuzz::ttf_parser::Face<'_>> {
    rustybuzz::ttf_parser::Face::parse((*fd.data).as_ref(), fd.index).ok()
}

